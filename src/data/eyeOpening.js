// Closed Catmull-Rom through those points, in `scale` units: 1 → the 0..1
// objectBoundingBox space, 100 → the lid's 0..100 viewBox.
const openingPath = (scale) => {
  const p = POINTS.map(([x, y]) => [x * scale, y * scale]);
  const n = p.length;
  const f = (v) => v.toFixed(scale === 1 ? 4 : 2);
  let d = `M ${f(p[0][0])},${f(p[0][1])}`;
  for (let i = 0; i < n; i++) {
    const [x0, y0] = p[(i - 1 + n) % n];
    const [x1, y1] = p[i];
    const [x2, y2] = p[(i + 1) % n];
    const [x3, y3] = p[(i + 2) % n];
    d +=
      ` C ${f(x1 + (x2 - x0) / 6)},${f(y1 + (y2 - y0) / 6)}` +
      ` ${f(x2 - (x3 - x1) / 6)},${f(y2 - (y3 - y1) / 6)}` +
      ` ${f(x2)},${f(y2)}`;
  }
  return `${d} Z`;
};

export const EYE_OPENING_01 = openingPath(1);
export const EYE_OPENING_100 = openingPath(100);